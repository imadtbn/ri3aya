#!/usr/bin/env python3
"""Generate a hashed, bounded public release snapshot. Never cache private data."""
from pathlib import Path
from bs4 import BeautifulSoup
from urllib.parse import urlsplit, unquote
import hashlib, json, argparse
ROOT=Path(__file__).resolve().parents[1]

def build():
    pages=[ROOT/'index.html', ROOT/'offline.html', *sorted((ROOT/'pages').rglob('*.html'))]
    files={p.relative_to(ROOT).as_posix() for p in pages}
    files.add('manifest.json'); files.add('search/index.json')
    for p in pages:
        soup=BeautifulSoup(p.read_text(),'html.parser')
        for tag in soup.select('script[src],link[href],img[src]'):
            if tag.name=='link' and not set(tag.get('rel',[])) & {'stylesheet','icon','apple-touch-icon','manifest'}: continue
            value=tag.get('src') or tag.get('href')
            url=urlsplit(value)
            if url.scheme or url.netloc: continue
            target=(p.parent/unquote(url.path)).resolve()
            assert target.is_relative_to(ROOT) and target.is_file(), f'Missing snapshot asset: {value}'
            files.add(target.relative_to(ROOT).as_posix())
        for img in soup.select('img[srcset]'):
            for variant in img['srcset'].split(','):
                target=(p.parent/variant.strip().split()[0]).resolve();files.add(target.relative_to(ROOT).as_posix())
    # WHO files are local dependencies of the existing growth engine.
    files.update(p.relative_to(ROOT).as_posix() for p in (ROOT/'content/medical').rglob('*') if p.is_file() and p.suffix in ('.csv','.json'))
    # PWA icons and shortcut destinations are explicit public assets.
    manifest=json.loads((ROOT/'manifest.json').read_text())
    files.update(icon['src'] for icon in manifest['icons'])
    ordered=sorted(files)
    size=sum((ROOT/f).stat().st_size for f in ordered)
    assert size < 6 * 1024 * 1024, f'Snapshot exceeds 6 MiB budget: {size}'
    fingerprints=[f+':'+hashlib.sha256((ROOT/f).read_bytes()).hexdigest() for f in [*ordered,'service-worker.js']]
    revision=hashlib.sha256('\n'.join(fingerprints).encode()).hexdigest()[:20]
    config='/* Generated by scripts/build_pwa.py. */\nself.RI3AYA_PWA = '+json.dumps({'revision':revision,'files':ordered},ensure_ascii=False,separators=(',',':'))+';\n'
    return config,len(ordered),size

if __name__=='__main__':
    parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
    config,count,size=build(); target=ROOT/'pwa/config.js'
    if args.check:
        assert target.read_text()==config, 'PWA release snapshot is stale. Run build_pwa.py last.'
    else: target.parent.mkdir(exist_ok=True);target.write_text(config)
    print(f'PWA snapshot: {count} files, {size} bytes; verified.' if args.check else f'PWA snapshot: {count} files, {size} bytes; generated.')
